const API_BASE = "http://127.0.0.1:8000";

// Typing effect configuration
function typeText(element, text, speed = 8) {
    return new Promise((resolve) => {
        element.innerHTML = "";
        let i = 0;
        function typing() {
            if (i < text.length) {
                element.innerHTML += text.charAt(i);
                i++;
                setTimeout(typing, speed);
            } else {
                resolve();
            }
        }
        typing();
    });
}

function showUIElem(id) {
    const el = document.getElementById(id);
    if(el) el.style.display = "flex";
}

function hideUIElem(id) {
    const el = document.getElementById(id);
    if(el) el.style.display = "none";
}

async function generatePlan() {
    const userInput = document.getElementById("userInput").value.trim();
    if (!userInput) {
        alert("Please enter a website type or industry to build!");
        return;
    }

    // UI resets
    hideUIElem("resultContainer");
    hideUIElem("confirmButtons");
    hideUIElem("codeButton");
    showUIElem("loader");
    
    document.getElementById("resultText").innerHTML = "";
    document.getElementById("systemMessage").innerHTML = "";

    try {
        const response = await fetch(`${API_BASE}/plan`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ message: userInput })
        });

        const data = await response.json();
        hideUIElem("loader");
        document.getElementById("resultContainer").style.display = "block";
        
        await typeText(document.getElementById("resultText"), data.plan || "No plan generated", 5);
        
        document.getElementById("systemMessage").innerText = data.message || "";
        showUIElem("confirmButtons");

    } catch (error) {
        hideUIElem("loader");
        document.getElementById("resultContainer").style.display = "block";
        document.getElementById("resultText").innerText = "❌ Error connecting to backend. Make sure the FastAPI server is running.";
        console.error("Generate Plan Error:", error);
    }
}

async function confirmPlan(answer) {
    hideUIElem("confirmButtons");
    document.getElementById("systemMessage").innerText = "Processing Your Request...";

    try {
        const response = await fetch(`${API_BASE}/confirm-plan`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ answer: answer })
        });
        
        const data = await response.json();
        
        if (data.status === "plan_accepted") {
            document.getElementById("systemMessage").innerText = data.message;
            showUIElem("codeButton");
        } else if (data.status === "plan_regenerated") {
            document.getElementById("resultText").innerText = "";
            await typeText(document.getElementById("resultText"), data.plan, 5);
            document.getElementById("systemMessage").innerText = data.message;
            showUIElem("confirmButtons");
        } else {
            document.getElementById("systemMessage").innerText = data.message || "Done.";
        }

    } catch (error) {
        document.getElementById("systemMessage").innerText = "❌ Error sending confirmation.";
        showUIElem("confirmButtons"); // Re-show on failure
        console.error("Confirm Plan Error:", error);
    }
}

async function generateCode() {
    hideUIElem("codeButton");
    document.getElementById("systemMessage").innerText = "🚀 Generating Code Magic! Please wait...";
    
    try {
        const response = await fetch(`${API_BASE}/generate-code`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ answer: "yes" })
        });
        
        const data = await response.json();
        
        if (data.status === "code_generated") {
            document.getElementById("systemMessage").innerText = "✅ Code successfully generated by Team-2 Generator!";
            console.log("Generated Code:", data.generated_code);
        } else {
            document.getElementById("systemMessage").innerText = "❌ Failed to generate code. Error: " + data.message;
        }

    } catch (error) {
        document.getElementById("systemMessage").innerText = "❌ Connection failed. Is Team-2 Generator running on port 3000?";
        console.error("Generate Code Error:", error);
    }
}

// Enter key support
document.getElementById("userInput").addEventListener("keypress", function(event) {
    if (event.key === "Enter") {
        generatePlan();
    }
});